"""
Week 8 - Render the two evidence charts for the LinkedIn/X posts.

Writes presentation/week8/post_images/:
  06_ds_contract_tests.png    Data Science contract tests C1-C15: 11/15 -> 12/15 -> 15/15
  07_release_gate_chart.png   Release gate: model AUC vs the single rule Age >= 65

Images 01-05 in the same folder are real VS Code screenshots (code and live terminal runs),
not generated by this script.

Usage: python scripts/week8_post_images.py
"""
import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
EVID = ROOT / "reports" / "week8" / "evidence"
OUT = ROOT / "presentation" / "week8" / "post_images"
OUT.mkdir(parents=True, exist_ok=True)

# --- Chart styling (same palette as the Week 7 post images) -------------------------
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
GOOD, CRITICAL, SERIES1, SERIES2 = "#0ca30c", "#d03b3b", "#2a78d6", "#eb6834"
plt.rcParams.update({"font.family": "DejaVu Sans", "text.color": INK, "axes.labelcolor": INK2,
                     "xtick.color": INK2, "ytick.color": INK2})

# --- 3. DS contract tests C1-C15 across the three runs -------------------------------
tests = list(csv.DictReader(open(EVID / "ds_contract" / "B_mle_pipeline_vs_ds_contract.csv", newline="")))
failed_7nov = {"C3", "C4", "C5", "C13"}       # DS_Handoff_Response.md (7 Nov)
failed_8nov = {"C3", "C4", "C5"}              # DS_Reply_2.md (8 Nov, C13 fixed by D-09)
runs = [("7 Nov\nfirst run", failed_7nov), ("8 Nov\nafter D-08/D-09", failed_8nov),
        ("8 Nov\nDS v1.1 strict", {t["ID"] for t in tests if t["Result"] != "PASS"})]
fig = plt.figure(figsize=(12, 8.6), dpi=150)
fig.patch.set_facecolor(SURFACE)
fig.text(0.04, 0.94, "Data Science contract tests against my pipeline", fontsize=19, weight="bold")
totals = "   →   ".join(f"{15 - len(f)}/15" for _, f in runs)
fig.text(0.04, 0.898, f"Same 15 tests, three runs:  {totals}.  The failures were policy differences, not crashes.",
         fontsize=12, color=INK2)
cols = [0.04, 0.10, 0.64, 0.76, 0.88]
y = 0.835
for x, h in zip(cols, ["ID", "Scenario"] + [r[0] for r in runs]):
    fig.text(x, y, h, fontsize=10, weight="bold", color=INK2, va="center")
y -= 0.03
for t in tests:
    y -= 0.047
    fig.add_artist(plt.Line2D([0.04, 0.96], [y + 0.025, y + 0.025], color=GRID, lw=0.8))
    fig.text(cols[0], y, t["ID"], fontsize=10.5, color=INK2, va="center")
    sc = t["Scenario"] if len(t["Scenario"]) <= 80 else t["Scenario"][:78] + "…"
    fig.text(cols[1], y, sc, fontsize=10.5, va="center")
    for x, (_, failed) in zip(cols[2:], runs):
        ok = t["ID"] not in failed
        fig.text(x, y, "✓ PASS" if ok else "✗ FAIL", fontsize=10.5, weight="bold",
                 color=GOOD if ok else CRITICAL, va="center")
fig.text(0.04, 0.045, "Fix: one shared contract — bad rows rejected with a reason, a status on every row, "
         "empty input → empty output.", fontsize=9.5, color=INK2)
fig.text(0.04, 0.02, "Source: reports/week8/evidence/ds_contract/, reports/week8/DS_Reply_2.md, DS_Reply_3.md",
         fontsize=8.5, color=INK2)
fig.savefig(OUT / "06_ds_contract_tests.png", facecolor=SURFACE)
plt.close(fig)
print("wrote", OUT / "06_ds_contract_tests.png")

# --- 4. Release gate: model vs the single rule Age >= 65 --------------------------------
gate = json.loads((EVID / "release_gate_high_risk.json").read_text())
auc = gate["rule_restatement_check"]["holdout_auc"]
bars = [("Shuffled labels (chance)", gate["metrics"]["shuffle_test"]["null_auc_mean"], GRID),
        ("My High-Risk model (6 inputs)", auc["model_all_6_inputs"], SERIES1),
        ("Same model, Age only", auc["random_forest_on_Age_only"], SERIES2),
        ("One rule: Age ≥ 65", auc["rule_component_Age>=65_alone"], SERIES2)]
fig, ax = plt.subplots(figsize=(11, 6), dpi=150)
fig.patch.set_facecolor(SURFACE)
ax.set_facecolor(SURFACE)
labels = [b[0] for b in bars][::-1]
vals = [b[1] for b in bars][::-1]
colors = [b[2] for b in bars][::-1]
ax.barh(labels, vals, color=colors, height=0.56)
for i, v in enumerate(vals):
    ax.text(v + 0.006, i, f"{v:.3f}", va="center", fontsize=12, weight="bold", color=INK)
ax.axvline(0.60, color=INK2, lw=1, ls=(0, (4, 3)))
ax.text(0.603, 3.42, "release gate: AUC ≥ 0.60", fontsize=9.5, color=INK2, va="bottom")
ax.set_xlim(0.4, 0.78)
ax.set_xlabel("ROC-AUC on the locked hold-out (n = 1,250)")
for s in ("top", "right", "left"):
    ax.spines[s].set_visible(False)
ax.spines["bottom"].set_color(GRID)
ax.tick_params(axis="y", length=0, labelsize=11.5, labelcolor=INK)
ax.grid(axis="x", color=GRID, lw=0.8)
ax.set_axisbelow(True)
fig.suptitle("It passed the release gate, but one rule does just as well", x=0.04, ha="left",
             fontsize=16, weight="bold", y=0.97)
fig.text(0.04, 0.875, "The label was built partly from Age ≥ 65, so the model mostly restates it.  "
         "Verdict: DEMO ONLY, not for patient decisions.", fontsize=11, color=INK2)
fig.text(0.04, 0.02, "Source: reports/week8/evidence/release_gate_high_risk.json  ·  "
         "python scripts/week8_release_gate.py", fontsize=8.5, color=INK2)
fig.subplots_adjust(left=0.27, right=0.95, top=0.8, bottom=0.15)
fig.savefig(OUT / "07_release_gate_chart.png", facecolor=SURFACE)
plt.close(fig)
print("wrote", OUT / "07_release_gate_chart.png")
